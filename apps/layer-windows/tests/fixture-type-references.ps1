function Test-FixtureTypeReferences([IO.FileInfo[]]$Files,[string[]]$RequiredTypes=@()){
$asts=@{};$definitions=@{};$imports=@{};$unresolved=[Collections.Generic.List[string]]::new();$replays=@()
foreach($file in $files){
    $ast=[Management.Automation.Language.Parser]::ParseFile($file.FullName,[ref]$null,[ref]$null)
    $asts[$file.FullName]=$ast
    $imports[$file.FullName]=@($ast.FindAll({param($n)$n -is [Management.Automation.Language.StringConstantExpressionAst] -and $n.Value.EndsWith('.ps1')},$true)|ForEach-Object {
        $leaf=Split-Path $_.Value -Leaf
        $files|Where-Object Name -eq $leaf|ForEach-Object FullName
    }|Sort-Object -Unique)
    foreach($command in $ast.FindAll({param($n)$n -is [Management.Automation.Language.CommandAst] -and $n.GetCommandName() -eq 'Add-Type'},$true)){
        $parts=$command.CommandElements;$source=$null
        for($i=1;$i -lt $parts.Count;$i++){
            if($parts[$i] -isnot [Management.Automation.Language.CommandParameterAst]){continue}
            $parameter=$parts[$i].ParameterName
            if($parameter -notin @('TypeDefinition','MemberDefinition','Path')){continue}
            $value=if($parts[$i].Argument){$parts[$i].Argument}else{$parts[$i+1]}
            if($parameter -in @('TypeDefinition','MemberDefinition')){
                if($value -is [Management.Automation.Language.VariableExpressionAst]){
                    $name=$value.VariablePath.UserPath
                    $binding=@($ast.FindAll({param($n)$n -is [Management.Automation.Language.AssignmentStatementAst] -and $n.Left -is [Management.Automation.Language.VariableExpressionAst] -and $n.Left.VariablePath.UserPath -eq $name}.GetNewClosure(),$true))
                    if($binding.Count -eq 1){$value=$binding[0].Right.Find({param($n)$n -is [Management.Automation.Language.StringConstantExpressionAst] -or $n -is [Management.Automation.Language.ExpandableStringExpressionAst]},$true)}
                }
                if($value -is [Management.Automation.Language.StringConstantExpressionAst]){$source=$value.Value}
                elseif($value -is [Management.Automation.Language.ExpandableStringExpressionAst] -and !$value.NestedExpressions.Count){$source=$value.Value}
                elseif($value -is [Management.Automation.Language.MemberExpressionAst] -and $value.Member.Value -eq 'Value'){$replays+="$($file.Name):$($command.Extent.StartLineNumber): AST source replay; references checked against original declarations"}
                else{$unresolved.Add("$($file.Name):$($command.Extent.StartLineNumber): nonliteral Add-Type source")}
                if($source -and $parameter -eq 'MemberDefinition'){
                    $wrapper=@{Namespace='Microsoft.PowerShell.Commands.AddType.AutoGeneratedTypes'}
                    for($j=1;$j -lt $parts.Count;$j++){
                        if($parts[$j] -is [Management.Automation.Language.CommandParameterAst] -and $parts[$j].ParameterName -in @('Name','Namespace')){
                            $argument=if($parts[$j].Argument){$parts[$j].Argument}else{$parts[$j+1]}
                            if($argument -isnot [Management.Automation.Language.StringConstantExpressionAst]){throw "Nonliteral MemberDefinition wrapper in $($file.Name)"}
                            $wrapper[$parts[$j].ParameterName]=$argument.Value
                        }
                    }
                    if(!$wrapper.Name){throw "Missing MemberDefinition name in $($file.Name)"}
                    $source="namespace $($wrapper.Namespace) { public class $($wrapper.Name) { $source } }"
                }
            }else{
                if($value.Extent.Text.Contains('.dll')){continue}
                if($value -is [Management.Automation.Language.VariableExpressionAst]){
                    $name=$value.VariablePath.UserPath
                    $binding=$ast.Find({param($n)$n -is [Management.Automation.Language.ParameterAst] -and $n.Name.VariablePath.UserPath -eq $name}.GetNewClosure(),$true)
                    if($binding){$value=$binding.DefaultValue}
                }
                $paths=@($value.FindAll({param($n)$n -is [Management.Automation.Language.StringConstantExpressionAst] -and $n.Value.EndsWith('.cs')},$true))
                if($value -is [Management.Automation.Language.StringConstantExpressionAst] -and $value.Value.EndsWith('.cs')){$paths=@($value)}
                if($paths.Count -eq 1){
                    $base=if($value.Extent.Text.Contains('$repo')){(Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path}else{$file.DirectoryName}
                    $path=[IO.Path]::GetFullPath((Join-Path $base $paths[0].Value))
                    if(Test-Path -LiteralPath $path){$source=[IO.File]::ReadAllText($path)}
                    else{$unresolved.Add("$($file.Name):$($command.Extent.StartLineNumber): unresolved Add-Type path $path")}
                }else{$unresolved.Add("$($file.Name):$($command.Extent.StartLineNumber): nonliteral Add-Type path")}
            }
        }
        if(!$source){continue}
        $tree=[Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree]::ParseText($source)
        if(@($tree.GetDiagnostics()|Where-Object Severity -eq Error).Count){throw "Invalid C# syntax in $($file.Name):$($command.Extent.StartLineNumber)"}
        foreach($type in $tree.GetRoot().DescendantNodes()|Where-Object {$_ -is [Microsoft.CodeAnalysis.CSharp.Syntax.BaseTypeDeclarationSyntax]}){
            $name=$type.Identifier.ValueText;$parent=$type.Parent
            while($parent){
                if($parent -is [Microsoft.CodeAnalysis.CSharp.Syntax.BaseTypeDeclarationSyntax]){$name=$parent.Identifier.ValueText+'+'+$name}
                elseif($parent -is [Microsoft.CodeAnalysis.CSharp.Syntax.BaseNamespaceDeclarationSyntax]){$name=$parent.Name.ToString()+'.'+$name}
                $parent=$parent.Parent
            }
            $members=@($type.Members|ForEach-Object {
                if($_ -is [Microsoft.CodeAnalysis.CSharp.Syntax.EnumMemberDeclarationSyntax]){$_.Identifier.ValueText}
                elseif($_.Modifiers.ValueText -contains 'public' -and ($_.Modifiers.ValueText -contains 'static' -or $_.Modifiers.ValueText -contains 'const')){
                    if($_ -is [Microsoft.CodeAnalysis.CSharp.Syntax.FieldDeclarationSyntax]){$_.Declaration.Variables.Identifier.ValueText}
                    elseif($_.PSObject.Properties['Identifier']){$_.Identifier.ValueText}
                }
            })
            $constructors=@($type.Members|Where-Object {$_ -is [Microsoft.CodeAnalysis.CSharp.Syntax.ConstructorDeclarationSyntax] -and $_.Modifiers.ValueText -notcontains 'static'})
            $arities=@()
            if($type -is [Microsoft.CodeAnalysis.CSharp.Syntax.StructDeclarationSyntax]){$arities+=@{min=0;max=0}}
            if($type.Modifiers.ValueText -notcontains 'static' -and $type.Modifiers.ValueText -notcontains 'abstract'){
                if(!$constructors.Count -and $type -is [Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax] -and $type.Modifiers.ValueText -contains 'public'){$arities+=@{min=0;max=0}}
                foreach($constructor in $constructors|Where-Object {$_.Modifiers.ValueText -contains 'public'}){
                    $parameters=@($constructor.ParameterList.Parameters)
                    $arities+=@{min=@($parameters|Where-Object {!$_.Default -and $_.Modifiers.ValueText -notcontains 'params'}).Count;max=if(@($parameters|Where-Object {$_.Modifiers.ValueText -contains 'params'}).Count){[int]::MaxValue}else{$parameters.Count}}
                }
            }
            $row=@{file=$file.FullName;name=$name;members=$members;arities=$arities;source=$source}
            if(!$definitions.ContainsKey($name)){$definitions[$name]=@()}
            $definitions[$name]+=$row
        }
    }
}
$failures=[Collections.Generic.List[string]]::new();$checks=0;$seen=@{}
foreach($file in $files){
    $scope=@($file.FullName);$pending=@($file.FullName)
    while($pending.Count){$next=@();foreach($path in $pending){foreach($import in $imports[$path]){if($import -notin $scope){$scope+=$import;$next+=$import}}};$pending=$next}
    foreach($node in $asts[$file.FullName].FindAll({param($n)$n -is [Management.Automation.Language.TypeExpressionAst] -or $n -is [Management.Automation.Language.TypeConstraintAst]},$true)){
        $name=$node.TypeName.FullName;$root=($name -split '\+')[0]
        if(!$definitions.ContainsKey($root)){continue}
        $seen[$root]=$true
        $local=@($definitions[$root]|Where-Object file -eq $file.FullName)
        if(!$local.Count){$local=@($definitions[$root]|Where-Object {$_.file -in $scope})}
        if(!$local.Count){
            $local=@($definitions[$root]|Where-Object { (Split-Path $_.file -Parent) -eq (Resolve-Path (Join-Path $PSScriptRoot '../scripts')).Path })
            if(!$local.Count){$local=@($definitions[$root])}
        }
        $sources=@($local.source|Sort-Object -Unique)
        if($sources.Count -ne 1){$failures.Add("$($file.Name):$($node.Extent.StartLineNumber): ambiguous custom type [$root]");continue}
        $definition=@($definitions[$name]|Where-Object {$_.file -eq $local[0].file -and $_.source -eq $sources[0]})
        $checks++
        if(!$definition.Count){$failures.Add("$($file.Name):$($node.Extent.StartLineNumber): missing custom type [$name]");continue}
        $parent=$node.Parent
        if($parent -is [Management.Automation.Language.MemberExpressionAst] -and $parent.Static -and $parent.Expression -eq $node){
            $member=$parent.Member.Value
            if($member -eq 'new'){
                $count=if($parent.Arguments){$parent.Arguments.Count}else{0}
                if(!@($definition[0].arities|Where-Object {$count -ge $_.min -and $count -le $_.max}).Count){$failures.Add("$($file.Name):$($node.Extent.StartLineNumber): missing public constructor [$name]::new with $count arguments")}
            }elseif($member -and $member -notin $definition[0].members){$failures.Add("$($file.Name):$($node.Extent.StartLineNumber): missing public static member [$name]::$member")}
        }
    }
}
$replays|Write-Output
foreach($name in $RequiredTypes){if(!$definitions.ContainsKey($name) -or !$seen.ContainsKey($name)){throw "Custom type coverage missing [$name]"}}
if($unresolved.Count -or $failures.Count){throw ((@($unresolved)+@($failures)) -join "`n")}
"Fixture custom type references passed $checks checks against actual C# syntax."
}
Test-FixtureTypeReferences @(Get-ChildItem (Join-Path $PSScriptRoot '../scripts'),$PSScriptRoot -Filter '*.ps1' -File) @('Capy.GlassWindow','Capy.SelectionDpi')
$directory=Join-Path (Resolve-Path (Join-Path $PSScriptRoot '../../..')) ('artifacts/windows/fixture-type-references/'+[guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($directory)|Out-Null
try{
    $real=Join-Path $directory 'real.ps1';$mock=Join-Path $directory 'mock.ps1';$consumer=Join-Path $directory 'consumer.ps1'
    [IO.File]::WriteAllText($mock,"Add-Type -TypeDefinition 'public class GuardOwner { public struct Missing {} public static void MissingMember() {} }'")
    $cases=@(
        @{source='public class GuardOwner { public struct Present {} public static void Good() {} }';reference='[GuardOwner+Present]::new();[GuardOwner]::Good()';error=$null},
        @{source='public class GuardOwner {}';reference='[GuardOwner+Missing]::new()';error='missing custom type [GuardOwner+Missing]'},
        @{source='public class GuardOwner {}';reference='[GuardOwner]::MissingMember()';error='missing public static member [GuardOwner]::MissingMember'},
        @{source='public class GuardOwner { private static void Hidden() {} public void Instance() {} }';reference='[GuardOwner]::Hidden();[GuardOwner]::Instance()';error='missing public static member'},
        @{source='public class GuardOwner { private GuardOwner() {} }';reference='[GuardOwner]::new()';error='missing public constructor'},
        @{source='public struct GuardOwner {}';reference='[GuardOwner]::new()';error=$null},
        @{source='public static class GuardOwner {}';reference='[GuardOwner]::new()';error='missing public constructor'}
    )
    foreach($case in $cases){
        [IO.File]::WriteAllText($real,"Add-Type -TypeDefinition '$($case.source)'")
        [IO.File]::WriteAllText($consumer,". './real.ps1'`n$($case.reference)")
        $failure=$null;try{$null=Test-FixtureTypeReferences @(Get-Item $real,$mock,$consumer)}catch{$failure=$_.Exception.Message}
        if($case.error){if(!$failure -or !$failure.Contains($case.error)){throw "Guard control did not reject $($case.reference): $failure"}}
        elseif($failure){throw $failure}
    }
    [IO.File]::WriteAllText($real,"Add-Type -Name GuardOwner -Namespace Guard -MemberDefinition 'public static int Good; private static int Hidden;'`n[Guard.GuardOwner]::Good")
    $null=Test-FixtureTypeReferences @(Get-Item $real) @('Guard.GuardOwner')
    [IO.File]::AppendAllText($real,"`n[Guard.GuardOwner]::Hidden")
    $failure=$null;try{$null=Test-FixtureTypeReferences @(Get-Item $real)}catch{$failure=$_.Exception.Message}
    if(!$failure -or !$failure.Contains('missing public static member [Guard.GuardOwner]::Hidden')){throw 'MemberDefinition private member control was accepted'}
    'Fixture type guard controls passed: nested types, static visibility, constructors, duplicate mocks and MemberDefinition.'
}finally{[IO.Directory]::Delete($directory,$true)}
