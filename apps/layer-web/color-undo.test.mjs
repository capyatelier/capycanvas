import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {createDrawing} from './new-drawing-fixture.mjs';

export async function checkColorUndo({call,evaluate,settle}) {
  const directory=process.env.LAYER_TEST_ARTIFACTS||'artifacts/color-undo/web';
  await mkdir(directory,{recursive:true});
  const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const wait=async expression=>{for(let i=0;i<300;i++){if(await evaluate(expression)){await settle();return;}await pause(30);}throw Error(`Timed out: ${expression}`);};
  const plain=expression=>evaluate(`JSON.parse(JSON.stringify(${expression},(_,v)=>typeof v==="bigint"?Number(v):v))`);
  const send=async action=>{await evaluate(`layerApp.dispatch(${JSON.stringify(action)})`);await settle();};
  const shot=async name=>writeFile(`${directory}/${name}.png`,Buffer.from((await call('Page.captureScreenshot',{format:'png'})).data,'base64'));
  const colors=()=>plain('layerApp.state().colors');
  const foreground=async()=>JSON.stringify((await colors()).foreground);
  const intensity=()=>evaluate('layerApp.app.color_panel().intensity');
  const rect=selector=>evaluate(`(()=>{const r=document.querySelector(${JSON.stringify(selector)})?.getBoundingClientRect();if(!r?.width)throw Error('Missing '+${JSON.stringify(selector)});return r.toJSON()})()`);
  const mouse=async(type,[x,y],button='left')=>call('Input.dispatchMouseEvent',{type,x,y,button,buttons:type==='mouseReleased'?0:button==='left'?1:2,clickCount:1,pointerType:'mouse'});
  const stroke=async points=>{await mouse('mousePressed',points[0]);for(const p of points.slice(1)){await pause(25);await mouse('mouseMoved',p);}await mouse('mouseReleased',points.at(-1));await settle();await pause(150);};
  const touches=async(type,points)=>call('Input.dispatchTouchEvent',{type,touchPoints:points.map(([x,y],i)=>({id:i+1,x,y}))});
  const touchStroke=async points=>{await touches('touchStart',[points[0]]);for(const p of points.slice(1)){await pause(25);await touches('touchMove',[p]);}await touches('touchEnd',[]);await settle();await pause(150);};
  const fingerTap=async points=>{await touches('touchStart',points);await pause(60);await touches('touchEnd',[]);await settle();await pause(200);};
  const escape=async()=>{for(const type of ['keyDown','keyUp'])await call('Input.dispatchKeyEvent',{type,key:'Escape',code:'Escape',windowsVirtualKeyCode:27});await settle();};
  const menuItem=label=>evaluate(`(()=>{const menu=document.querySelector('.panel-context-menu:popover-open');if(!menu)return null;const row=[...menu.querySelectorAll('button')].find(b=>b.querySelector('.menu-label')?.textContent===${JSON.stringify(label)});if(!row)return {open:true};const r=row.getBoundingClientRect();return {open:true,enabled:!row.disabled,point:[r.x+r.width/2,r.y+r.height/2]}})()`);
  const rightClick=async p=>{await mouse('mousePressed',p,'right');await mouse('mouseReleased',p,'right');await settle();await pause(150);};
  const undo=(await plain("layerApp.app.context_menu({kind:'color_wheel'})")).sections[0][0].label;
  const saved=await evaluate('layerApp.app.workspace_persistence()');
  const fixture=structuredClone(saved);fixture.layout.bubbles={bubbles:[],rings:[],kept:[]};
  fixture.layout.header={size:'medium',zones:[[{id:1,item:{kind:'capy'}}],[{id:2,item:{kind:'tool',control:{kind:'color'}}}],[]],next_id:3};
  await wait('layerApp.startupTimes.complete!==null&&layerApp.app.brush_ready()');
  await send({type:'invoke',command:'new_document'});
  await evaluate(createDrawing({width:1024,height:768,depth:'F16'}));
  await wait('layerApp.app.brush_ready()&&layerApp.app.document_color().depth==="F16"');
  for(const theme of ['light','dark']) {
    await call('Emulation.setTouchEmulationEnabled',{enabled:false});
    await send({type:'restore_workspace',workspace:fixture});await send({type:'set_theme',theme});
    await send({type:'customize',action:{type:'set_panel_visible',panel:'color',visible:true}});
    await send({type:'move_panel',panel:'color',target:{kind:'float',position:[260,180]}});
    await pause(400);
    await send({type:'color',action:{op:'select',slot:'foreground'}});
    await send({type:'set_color',rgba:[.2,.7,.45,1]});
    await pause(200);
    const wheel=await rect('.color-wheel-control canvas.color-wheel'),geometry=(await plain('layerApp.app.color_panel()')).geometry;
    const at=(radius,degrees)=>[wheel.x+wheel.width*(geometry.center[0]+radius*Math.cos(degrees*Math.PI/180)),wheel.y+wheel.height*(geometry.center[1]+radius*Math.sin(degrees*Math.PI/180))];
    const ring=at((geometry.inner+geometry.outer)/2,0),field=r=>at(geometry.disc_radius*r,135);
    const start=await foreground();
    await stroke([at(geometry.disc_radius*.3,-40),at(geometry.disc_radius*.5,10),at(geometry.disc_radius*.4,60)]);
    const dragged=await foreground();
    assert.notEqual(dragged,start,`${theme}: dragging on the panel wheel picks`);
    await rightClick(ring);
    const item=await menuItem(undo);
    assert.ok(item?.enabled,`${theme}: right-clicking the hue ring offers ${undo}: ${JSON.stringify(item)}`);
    await shot(`${theme}-panel-menu`);
    await mouse('mousePressed',item.point);await mouse('mouseReleased',item.point);await settle();
    assert.equal(await foreground(),start,`${theme}: one undo restores the color from before the whole drag`);

    const outside=await evaluate(`(()=>{const c=document.querySelector('.color-wheel-control canvas.color-wheel'),r=c.getBoundingClientRect(),g=${JSON.stringify(geometry)};
      for(let i=1;i<20;i++)for(let j=1;j<20;j++){const x=r.x+r.width*i/20,y=r.y+r.height*j/20;
        if(document.elementFromPoint(x,y)===c&&Math.hypot(i/20-g.center[0],j/20-g.center[1])>g.outer+.02)return [x,y];}})()`);
    assert.ok(outside,`${theme}: the wheel canvas has corners outside the ring`);
    await rightClick(outside);
    const panelMenu=await menuItem(undo);
    assert.ok(panelMenu?.open&&!panelMenu.point,`${theme}: outside the ring the panel keeps its own menu`);
    await escape();

    await call('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
    const fingers=[field(.25),field(-.25),at((geometry.inner+geometry.outer)/2,90)];
    await fingerTap(fingers);
    assert.equal(await foreground(),dragged,`${theme}: a three-finger tap on the panel wheel redoes`);
    await fingerTap(fingers.slice(0,2));
    assert.equal(await foreground(),start,`${theme}: a two-finger tap on the panel wheel undoes`);
    await touchStroke([at(geometry.disc_radius*.3,-40),at(geometry.disc_radius*.5,10)]);
    assert.notEqual(await foreground(),start,`${theme}: a finger drag picks`);
    await touches('touchStart',[field(.4)]);await pause(30);await touches('touchStart',[field(.4),ring]);await pause(40);await touches('touchEnd',[]);await settle();await pause(200);
    assert.equal(await foreground(),start,`${theme}: the second finger retires the first finger's pick and the tap undoes the drag`);

    const stage=await rect('.color-wheel-control .color-wheel-square');
    const arc=async fraction=>{const p=(await evaluate(`layerApp.app.color_ui({type:'arc',size:${stage.width},fraction:${fraction}})`)).point;return [stage.x+p[0],stage.y+p[1]];};
    await call('Emulation.setTouchEmulationEnabled',{enabled:false});
    const stops=await intensity();
    await stroke([await arc(.4),await arc(.6),await arc(.8)]);
    assert.ok(await intensity()>stops+1,`${theme}: the arc raises the intensity`);
    await rightClick(await arc(.5));
    assert.ok((await menuItem(undo))?.enabled,`${theme}: the arc offers color undo`);
    await escape();
    await call('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
    await fingerTap([await arc(.3),await arc(.7)]);
    assert.equal(await intensity(),stops,`${theme}: a two-finger tap on the arc undoes the whole arc drag`);

    await call('Emulation.setTouchEmulationEnabled',{enabled:false});
    const from=await rect('[data-header-item="2"] .header-tool'),header=[from.x+from.width/2,from.y+from.height/2];
    await mouse('mousePressed',header);await pause(40);await mouse('mouseReleased',header);await settle();
    await wait('!!layerApp.state().customization.drawer');
    await stroke([header,[header[0],header[1]+10],[header[0],header[1]+100],[760,460]]);
    await wait('layerApp.app.bubbles().some(p=>p.view.kind==="color")');
    const id=Number(await evaluate('layerApp.app.bubbles().find(p=>p.view.kind==="color").view.id'));
    const center=async()=>{const r=await rect(`.tool-bubble[data-bubble="${id}"] .bubble-wheel`);return [r.x+r.width/2,r.y+r.height/2];};
    await pause(600);
    const c=await center(),before=await foreground();
    await call('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
    await touchStroke([[c[0]+20,c[1]-10],[c[0]-15,c[1]+10]]);
    const picked=await foreground();
    assert.notEqual(picked,before,`${theme}: the ring picks`);
    await fingerTap([[c[0]-25,c[1]],[c[0]+25,c[1]]]);
    assert.equal(await foreground(),before,`${theme}: a two-finger tap on the ring undoes`);
    assert.deepEqual(await center(),c,`${theme}: and leaves the ring where it is`);
    await fingerTap([[c[0]-25,c[1]],[c[0]+25,c[1]],[c[0],c[1]+30]]);
    assert.equal(await foreground(),picked,`${theme}: a three-finger tap on the ring redoes`);
    await call('Emulation.setTouchEmulationEnabled',{enabled:false});
    await rightClick(c);
    const bubbleItem=await menuItem(undo);
    assert.ok(bubbleItem?.enabled,`${theme}: the ring's menu offers ${undo}`);
    await shot(`${theme}-bubble-menu`);
    await mouse('mousePressed',bubbleItem.point);await mouse('mouseReleased',bubbleItem.point);await settle();
    assert.equal(await foreground(),before,`${theme}: the ring's menu undoes`);
  }
  await call('Emulation.setTouchEmulationEnabled',{enabled:false});
}
